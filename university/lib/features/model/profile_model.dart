class ProfileModel {
  final String name;
  final String jobTitle;
  final String email;
  final String location;
  final String phone;
  final String aboutMe;
  final String portfolioUrl;

  const ProfileModel({
    required this.name,
    required this.jobTitle,
    required this.email,
    required this.location,
    required this.phone,
    required this.aboutMe,
    required this.portfolioUrl,
  });
}